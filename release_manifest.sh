#!/bin/bash
#
# Write extensions.json (latest version, versions and arches per extension)
# from the repo's GitHub releases, and upload it to the 'manifest' release.
#
# Release tags look like <name>-v<version> or <name>-<version>. The bare <name>
# metadata releases, SHA256SUMS and the manifest release itself are ignored.
# The hub serves the uploaded asset as /extensions/manifest.json.
#
# Usage: ./release_manifest.sh [--no-upload] [output-file]
#   --no-upload   only write the file (default ./extensions.json); needs no write access.
#   RELEASES_JSON=<file>  read releases from a file instead of the GitHub API.

set -euo pipefail

manifest_tag="manifest"
manifest_asset="extensions.json"
pages="https://qopsc.github.io/sysext-bakery"

# Doc page URL for an extension: docs/<name>.md, or docs/<name with _>.md.
function doc_url() {
  local root="$1" name="$2" doc="$2"
  if [[ ! -f "${root}/docs/${name}.md" && -f "${root}/docs/${name//-/_}.md" ]] ; then
    doc="${name//-/_}"
  fi
  echo "${pages}/${doc}/"
}
# --

# build_manifest <releases.json> <docs-root> <name>...
# releases.json: array of {tag_name, draft, prerelease, assets:[{name}]}.
function build_manifest() {
  local releases="$1" root="$2"; shift 2
  local names
  names="$(for n in "$@"; do
    jq -n --arg n "$n" --arg d "$(doc_url "${root}" "$n")" '{name: $n, doc: $d}'
  done | jq -s .)"

  jq --argjson exts "${names}" --arg now "$(date -u +%Y-%m-%dT%H:%M:%SZ)" '
    def nums: [scan("[0-9]+|[A-Za-z]+") | (tonumber? // .)];
    # numeric compare; a pre-release (-rc1) sorts before its release.
    def vkey: capture("^(?<c>[^-+]*)(?<p>-[^+]*)?(?<b>\\+.*)?$")
      | [(.c | nums), (if .p then 0 else 1 end), ((.p // "") | nums), ((.b // "") | nums)];
    [.[] | select((.draft | not) and (.prerelease | not))] as $rel
    | {generated: $now,
       extensions: [ $exts[] | . as $e
         | [ $rel[] | select(.tag_name | startswith($e.name + "-") and (ltrimstr($e.name + "-") | test("^v?[0-9]")))
             | {tag: .tag_name,
                version: (.tag_name | ltrimstr($e.name + "-") | ltrimstr("v")),
                assets: [.assets[].name]} ] as $mine
         | ($mine | sort_by(.version | vkey) | reverse) as $sorted
         | $e + {latest: ($sorted[0].version // null),
                 versions: [$sorted[].version],
                 arches: ([$sorted[0] // empty | . as $r | $r.assets[]
                           | select(endswith(".raw") and startswith($r.tag + "-"))
                           | ltrimstr($r.tag + "-") | rtrimstr(".raw")] | sort)} ]
         | sort_by(.name)}' "${releases}"
}
# --

function main() {
  local upload=true
  if [[ ${1:-} == --no-upload ]] ; then upload=false; shift; fi
  local out="${1:-extensions.json}"

  cd "$(dirname "$0")"
  # shellcheck source=lib/libbakery.sh
  source "lib/libbakery.sh"

  releases="$(mktemp)"
  trap 'rm -f "${releases}"' EXIT
  if [[ -n ${RELEASES_JSON:-} ]] ; then
    cp "${RELEASES_JSON}" "${releases}"
  else
    gh api --paginate "repos/${bakery}/releases?per_page=100" \
      --jq '.[] | {tag_name, draft, prerelease, assets: [.assets[] | {name}]}' | jq -s . > "${releases}"
  fi

  local names=()
  mapfile -t names < <(./bakery.sh list --plain true)
  build_manifest "${releases}" "." "${names[@]}" > "${out}"
  echo "Wrote ${out}: $(jq '.extensions | length' "${out}") extensions"

  [[ ${upload} == true ]] || return 0

  # --latest=false: never the repo's "latest" release. No SHA256SUMS asset, so
  # release_meta.sh skips it.
  if ! gh release view "${manifest_tag}" -R "${bakery}" >/dev/null 2>&1 ; then
    gh release create "${manifest_tag}" -R "${bakery}" --latest=false \
      --title "Extension manifest" \
      --notes "Machine-readable list of extensions and versions. Regenerated by release_manifest.sh; do not edit."
  fi
  gh release upload "${manifest_tag}" "${out}#${manifest_asset}" -R "${bakery}" --clobber
}
# --

if [[ ${BASH_SOURCE[0]} == "$0" ]] ; then
  main "$@"
fi
